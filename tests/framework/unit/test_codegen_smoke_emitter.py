"""Unit tests for mcp_test_framework.test_code._codegen smoke-scenario emission.

Pins (Phase 999.2 -- GEN-03, GEN-04, GEN-05):
  - examples-present (single) -> real scenario w/ CreateVmParams(**{...}) and
    await tool("<name>").call(params)
  - examples-present (multi)  -> @pytest.mark.parametrize with positional
    example-{i} ids (Pitfall 4 -- stable parametrize IDs across operator edits)
  - examples absent/empty     -> pytest.skip(allow_module_level=True) with
    the EXACT grep-able reason text from D-02a; relative import still present
    (D-02 -- module fully importable)
  - 4-line header sentinel shared with <tool>.py via _render_header()
  - relative import `from .<mod> import <Pascal>Params` (Pitfall 2 guard)
  - @pytest.mark.asyncio(loop_scope="session") literal (Pitfall 1 guard)
  - operator-supplied example values json.dumps()-escaped
    (V5 input validation / Tampering mitigation; mirrors _codegen.py:582-590)
"""
from __future__ import annotations

import pytest
from mcp.types import Tool

from mcp_test_framework.test_code._codegen import _emit_smoke_scenario


_FIXED_TS = "2026-05-12T14:23:01+00:00"


def _t(name: str, *, input_schema: dict | None = None, output_schema: dict | None = None) -> Tool:
    return Tool(
        name=name,
        description=f"Test tool {name}",
        inputSchema=(
            input_schema
            if input_schema is not None
            else {"type": "object", "properties": {}, "required": []}
        ),
        outputSchema=output_schema,
    )


def _required_tool(name: str = "create_vm") -> Tool:
    return _t(name, input_schema={
        "type": "object",
        "properties": {
            "vmid": {"type": "integer"},
            "name": {"type": "string"},
        },
        "required": ["vmid", "name"],
    })


def test_emit_smoke_returns_string_with_header_sentinel() -> None:
    """Single-example branch returns a string with the 4-line header sentinel."""
    src = _emit_smoke_scenario(
        _required_tool("create_vm"),
        slug="homelab_mcp",
        server_name="homelab-mcp",
        server_version="0.5.2",
        timestamp=_FIXED_TS,
        examples=[{"vmid": 9001, "name": "smoke"}],
    )
    assert isinstance(src, str)
    assert "# AUTOGENERATED by mcp-test-framework gen-test-classes -- DO NOT HAND-EDIT." in src
    assert f"# Regenerated: {_FIXED_TS}" in src


