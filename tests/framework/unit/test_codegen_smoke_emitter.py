def test_emit_smoke_todo_branch_import_precedes_skip() -> None:
    """examples=None -> relative import appears BEFORE pytest.skip() (D-02 + research Q6)."""
    src = _emit_smoke_scenario(
        _required_tool("create_vm"),
        slug="homelab_mcp",
        server_name="homelab-mcp",
        server_version="0.5.2",
        timestamp=_FIXED_TS,
        examples=None,
    )
    import_pos = src.index("from .create_vm import CreateVmParams")
    skip_pos = src.index("pytest.skip(")
    assert import_pos < skip_pos, (
        "Relative import must appear BEFORE pytest.skip() so an ImportError "
        "surfaces as a real codegen bug rather than being masked by the skip."
    )


def test_emit_smoke_example_values_json_escaped() -> None:
    """Operator values with quotes/newlines are json.dumps()-escaped so they cannot inject source."""
    dangerous_value = 'vm-with-"quote"-and-\nnewline'
    import json
    safe_repr = json.dumps(dangerous_value)  # '"vm-with-\\"quote\\"-and-\\nnewline"'
    src = _emit_smoke_scenario(
        _required_tool("create_vm"),
        slug="homelab_mcp",
        server_name="homelab-mcp",
        server_version="0.5.2",
        timestamp=_FIXED_TS,
        examples=[{"name": dangerous_value}],
    )
    # The safe escaped form must appear in the source
    assert safe_repr in src
    # The raw unescaped value must NOT appear (would close the dict literal early)
    assert dangerous_value not in src
